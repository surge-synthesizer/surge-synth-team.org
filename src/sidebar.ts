import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

/*
 * A stand-in for Starlight's `autogenerate` sidebar option, which cannot be
 * used here.
 *
 * Starlight resolves an autogenerate directory by stripping a hardcoded
 * "src/content/docs/" from each entry's filePath (utils/navigation.js,
 * getRoutePathRelativeToCollectionRoot). Under the product-first layout the
 * files live in src/content/products/, so the strip is a no-op, nothing ever
 * matches the directory, and the group comes out empty. That is a third thing
 * tied to the old folder, alongside the lastUpdated and i18n features already
 * known to be.
 *
 * This reads the same folder at config time and returns the items Starlight
 * would have produced. astro.config.ts runs in Node, so the filesystem is
 * available; the alternative is hand-listing every release forever.
 */

const PRODUCTS = "./src/content/products";

/** Reads one frontmatter key. Indented keys count: label and order sit under `sidebar:`. */
function field(front: string, name: string) {
    const pattern = new RegExp("^[ \t]*" + name + ":[ \t]*(.+)$", "m");

    return pattern
        .exec(front)?.[1]
        ?.trim()
        .replace(/^['"]|['"]$/g, "");
}

/**
 * Sidebar items for one folder of docs, ordered by each page's sidebar.order.
 *
 * `hidden` pages are left out by default, matching Starlight's own
 * sidebar.hidden. Passing "hidden" returns exactly those instead, so they can
 * be gathered into a group of their own rather than vanishing.
 */
export function pagesIn(directory: string, include: "visible" | "hidden" = "visible") {
    const root = join(PRODUCTS, directory);

    return (
        readdirSync(root, { withFileTypes: true })
            .filter((entry) => entry.isFile() && /\.mdx?$/.test(entry.name))
            .map((entry) => {
                const text = readFileSync(join(root, entry.name), "utf8");
                const front = /^---\n([\s\S]*?)\n---/.exec(text)?.[1] ?? "";
                const name = entry.name.replace(/\.mdx?$/, "");

                return {
                    label: field(front, "label") ?? field(front, "title") ?? name,
                    slug: `${directory}/${name}`.replace(/\/index$/, ""),
                    order: Number(field(front, "order") ?? 0),
                    hidden: field(front, "hidden") === "true",
                };
            })
            /*
             * Honouring sidebar.hidden the way Starlight does for autogenerated
             * groups. Leaving a page out of the sidebar also takes it out of the
             * previous/next pagination, which is derived from it - which is the
             * point: unreleased notes should not sit in the reading order of
             * shipped ones.
             */
            .filter((entry) => entry.hidden === (include === "hidden"))
            .sort((a, b) => a.order - b.order)
            .map(({ label, slug }) => ({ label, slug }))
    );
}

/**
 * The nightly notes as a flat link rather than a group of one.
 *
 * A product only ever has a single set of nightly notes, and a collapsible
 * group wrapping one child costs a click to reveal what its own label could
 * have linked to. Returns an array so it spreads to nothing for a product
 * with no nightly notes yet, leaving no empty entry behind.
 */
export function nightlyIn(directory: string, label = "Nightly releases") {
    const pages = pagesIn(directory, "hidden");

    if (pages.length > 1) {
        throw new Error(`${directory}: ${pages.length} nightly pages, expected at most one`);
    }

    return pages.map((page) => ({ ...page, label }));
}
